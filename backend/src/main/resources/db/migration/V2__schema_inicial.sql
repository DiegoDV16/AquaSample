ALTER TABLE muestras ADD COLUMN IF NOT EXISTS marine_wave_height DOUBLE PRECISION;
ALTER TABLE muestras ADD COLUMN IF NOT EXISTS marine_sea_surface_temperature DOUBLE PRECISION;
ALTER TABLE muestras ADD COLUMN IF NOT EXISTS marine_wind_speed DOUBLE PRECISION;
ALTER TABLE muestras ADD COLUMN IF NOT EXISTS eliminado BOOLEAN;
ALTER TABLE muestras ADD COLUMN IF NOT EXISTS updated_at BIGINT;
