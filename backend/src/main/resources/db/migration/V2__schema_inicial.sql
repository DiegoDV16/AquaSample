-- Esquema base de AquaSample.
-- Se usa IF NOT EXISTS para poder aplicar sobre una base creada por Hibernate
-- (baseline 1) y también sobre una base vacía (Render).
CREATE TABLE IF NOT EXISTS centros_cultivo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(255) NOT NULL,
    comuna VARCHAR(255),
    estado VARCHAR(255),
    nombre VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS usuarios (
    id VARCHAR(255) PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255),
    nombres VARCHAR(255) NOT NULL,
    apellido_paterno VARCHAR(255),
    apellido_materno VARCHAR(255),
    rol_id BIGINT,
    estado VARCHAR(255),
    creado_en BIGINT
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_usuarios_email ON usuarios (email);

CREATE TABLE IF NOT EXISTS tramos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    centro_id BIGINT NOT NULL,
    tren VARCHAR(255) NOT NULL,
    linea VARCHAR(255) NOT NULL,
    longitud_cm INTEGER NOT NULL,
    estado VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS muestras (
    id VARCHAR(255) PRIMARY KEY,
    centro_id BIGINT,
    tramo_id BIGINT,
    operador_id VARCHAR(255),
    concesion VARCHAR(255) NOT NULL,
    tren VARCHAR(255),
    linea VARCHAR(255),
    tramo_longitud_cm VARCHAR(255),
    conteo_manual INTEGER,
    calibre_matrix CLOB,
    average_calibre DOUBLE PRECISION,
    marcas_conteo CLOB,
    conteo_asistido INTEGER,
    photo_count INTEGER,
    fotos CLOB,
    observaciones CLOB,
    tags CLOB,
    fecha_hora VARCHAR(255),
    timestamp BIGINT,
    estado VARCHAR(255),
    sincronizado BOOLEAN,
    operator_alias VARCHAR(255),
    marine_time VARCHAR(255),
    marine_wave_height DOUBLE PRECISION,
    marine_sea_surface_temperature DOUBLE PRECISION,
    marine_wind_speed DOUBLE PRECISION,
    eliminado BOOLEAN,
    updated_at BIGINT
);

-- Compatibilidad con bases creadas antes de los últimos campos.
